CREATE TABLE IF NOT EXISTS century_park_shots (
  id varchar(64) COLLATE utf8mb4_bin NOT NULL PRIMARY KEY,
  tenant_id varchar(64) COLLATE utf8mb4_bin NOT NULL,
  operator_id varchar(64) COLLATE utf8mb4_bin NOT NULL,
  request_id varchar(36) COLLATE utf8mb4_bin NOT NULL,
  customer_id varchar(128) COLLATE utf8mb4_bin NOT NULL,
  customer_name varchar(255) NOT NULL,
  recipient_phone varchar(32) NOT NULL,
  last_order_date varchar(40) NOT NULL,
  opportunity_key varchar(64) COLLATE utf8mb4_bin NOT NULL,
  fingerprint varchar(64) COLLATE utf8mb4_bin NOT NULL,
  approval_json json NOT NULL,
  policy_version varchar(40) NOT NULL,
  approved_at timestamp(3) NOT NULL,
  scheduled_for timestamp(3) NOT NULL,
  state varchar(32) NOT NULL,
  offer_state varchar(32) NOT NULL,
  message_id varchar(64) COLLATE utf8mb4_bin NULL,
  failure_reason text NULL,
  updated_at timestamp(3) NOT NULL,
  UNIQUE KEY uq_cpe_shot_request (tenant_id, request_id),
  UNIQUE KEY uq_cpe_shot_opportunity (tenant_id, customer_id, opportunity_key),
  KEY idx_cpe_shot_timeline (tenant_id, approved_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
