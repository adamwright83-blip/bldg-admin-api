// zombie night on the GPU: taze the dormant resident's zombie, program the shotgun, fire, watch it wreck a washer
import { chromium } from "@playwright/test";
import fs from "node:fs";
const out = "./shots-shotgun"; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--use-angle=metal", "--ignore-gpu-blocklist"] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = []; page.on("pageerror", e => errors.push(String(e)));
await page.goto("http://localhost:5178/growth/lantern-city?level=century-park-east&preview=synthetic");
await page.waitForFunction(() => window.__centuryParkEast?.ready, null, { timeout: 120000 });
const h = fn => page.evaluate(fn);
await h(() => window.__centuryParkEast.calm());
const vibe = await page.locator('[data-testid="century-park-east-3d"]').getAttribute("data-vibe");
if (vibe !== "zombie") await page.getByTestId("century-park-east-vibe").click();
await page.waitForTimeout(1200);
const open = page.getByTestId("century-park-east-open-slot");
await open.waitFor({ state: "attached", timeout: 30000 });
const slot = Number(await open.getAttribute("data-slot"));
console.log("open slot:", slot, "phase:", await open.getAttribute("data-phase"));
await page.evaluate(s => window.__centuryParkEast.taze(s), slot);
await page.waitForTimeout(900);
const st = await h(() => window.__centuryParkEast.state());
console.log("after taze: zombie", st.zombies[slot].state, "prompt:", st.prompt);
await page.screenshot({ path: `${out}/1-tazed.png` });
await page.getByTestId("century-park-east-prompt").click();
await page.getByTestId("century-park-east-shotgun").waitFor({ timeout: 5000 });
await page.screenshot({ path: `${out}/2-gun-step1.png` });
await page.getByTestId("century-park-east-opening").first().click();
await page.getByTestId("century-park-east-hypothesis").nth(1).click();
await page.screenshot({ path: `${out}/3-gun-shell.png` });
await page.getByTestId("century-park-east-shell").nth(1).click();
await page.locator('[data-testid="century-park-east-aim"][data-last="yes"]').first().click().catch(async () => page.getByTestId("century-park-east-aim").nth(20).click());
await page.screenshot({ path: `${out}/4-gun-aim.png` });
const text = await page.getByTestId("century-park-east-shotgun-text").inputValue();
console.log("text:", text);
console.log("fuse:", await page.getByTestId("century-park-east-fuse").innerText());
await page.getByTestId("century-park-east-fire").click();
await page.getByTestId("century-park-east-shotgun").waitFor({ state: "detached", timeout: 10000 });
let s2 = await h(() => window.__centuryParkEast.state());
console.log("after fire: zombie", s2.zombies[slot].state, "open slot now:", await open.getAttribute("data-slot").catch(() => "none"));
await page.evaluate(() => window.__centuryParkEast.teleport(1, 4.5, -2.2));
for (let i = 0; i < 60 && s2.wrecked === 0; i++) { await page.waitForTimeout(500); s2 = await h(() => window.__centuryParkEast.state()); if (i === 6) await page.screenshot({ path: `${out}/5-walking.png` }); }
console.log("wrecked:", s2.wrecked, "zombie:", s2.zombies[slot].state, s2.zombies[slot].floor, s2.zombies[slot].x.toFixed(1));
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/6-wrecked.png` });
console.log("HUD:", await page.getByTestId("century-park-east-wreck").innerText().catch(() => "n/a"));
console.log("pageerrors:", errors.length ? errors : "none");
await browser.close();
